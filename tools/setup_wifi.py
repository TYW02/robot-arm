#!/usr/bin/env python3
"""Creates config/wifi_credentials.h and config/wifi_log_config.h for the Pico.

Run from anywhere:   python3 tools/setup_wifi.py
Both files are gitignored, so your Wi-Fi password is never committed.
"""
import os, sys, getpass

here = os.path.dirname(os.path.abspath(__file__))
cfg = os.path.normpath(os.path.join(here, "..", "third_party", "mtk3smp-rp2040", "config"))
if not os.path.isdir(cfg):
    sys.exit("Can't find %s\nRun this from inside the robot-arm repo." % cfg)

def c_escape(s):
    out = ""
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch == '"' or ch == "\\":
            out += "\\" + ch
        elif 32 <= b < 127:
            out += ch
        else:
            out += "\\x%02X" % b
            out += '""'          # stop a following hex digit joining the escape
    return out

print("Pico Wi-Fi setup  (2.4 GHz network or phone hotspot only)\n")
ssid = input("Wi-Fi name (SSID, exact capitals/spaces): ").strip("\r\n")
pw = getpass.getpass("Wi-Fi password (typing is hidden): ")
if not ssid:
    sys.exit("SSID is empty.")
if len(pw) < 8:
    sys.exit("WPA2 passwords must be at least 8 characters.")
if any(ord(c) > 127 for c in ssid):
    print("\nWarning: the name has non-ASCII characters (emoji/accents). The Pico can fail to find it.")
    print("Safer: rename the hotspot to plain letters and numbers, then run this again.\n")

cred = os.path.join(cfg, "wifi_credentials.h")
with open(cred, "w") as f:
    f.write('''#ifndef WIFI_CREDENTIALS_H
#define WIFI_CREDENTIALS_H
/* Generated by tools/setup_wifi.py. Local only - gitignored, never commit. */
#define UTK_WIFI_CREDENTIALS_SET   1
#define UTK_WIFI_SSID       "%s"
#define UTK_WIFI_PASSWORD   "%s"
#define UTK_WIFI_AUTH       CYW43_AUTH_WPA2_AES_PSK
#endif /* WIFI_CREDENTIALS_H */
''' % (c_escape(ssid), c_escape(pw)))

logc = os.path.join(cfg, "wifi_log_config.h")
if not os.path.exists(logc):
    with open(logc, "w") as f:
        f.write('''#ifndef WIFI_LOG_CONFIG_H
#define WIFI_LOG_CONFIG_H
/* Used only when UTK_WIFI_LOG_BROADCAST is 0: laptop IPv4 address. */
#define UTK_WIFI_LOG_TARGET_A 192
#define UTK_WIFI_LOG_TARGET_B 168
#define UTK_WIFI_LOG_TARGET_C 1
#define UTK_WIFI_LOG_TARGET_D 100
/* 1 = send logs to the whole subnet, no laptop IP needed. 0 = send to the IP above. */
#define UTK_WIFI_LOG_BROADCAST 1
#endif /* WIFI_LOG_CONFIG_H */
''')
    print("Created", logc)
else:
    print("Kept existing", logc)
print("Created", cred)
print("\nNow rebuild and re-flash the Pico. Do not share the .uf2 (it contains your password).")
